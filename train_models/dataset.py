from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
from typing import Iterable

import numpy as np
import pandas as pd
import torch
from sklearn.preprocessing import StandardScaler
from torch.utils.data import DataLoader, Dataset

from config import SEQUENCE_LENGTH, TARGET_COL


COIN_ID_COLS = ["coin_BTC", "coin_ETH"]


@dataclass
class PreparedData:
    feature_cols: list[str]
    target_col: str
    sequence_length: int

    train_df: pd.DataFrame
    val_df: pd.DataFrame
    test_df: pd.DataFrame

    X_train_seq: np.ndarray
    y_train: np.ndarray
    X_val_seq: np.ndarray
    y_val: np.ndarray
    X_test_seq: np.ndarray
    y_test: np.ndarray

    X_train_flat: np.ndarray
    X_val_flat: np.ndarray
    X_test_flat: np.ndarray

    train_loader: DataLoader
    val_loader: DataLoader
    test_loader: DataLoader

    feature_scaler: StandardScaler
    target_scaler: StandardScaler


class CryptoSequenceDataset(Dataset):
    """
    Dataset used by LSTM and CNN-LSTM.

    X shape:
        [samples, 30, num_features]

    y shape:
        [samples, 1]
    """

    def __init__(self, X: np.ndarray, y: np.ndarray):
        self.X = torch.tensor(X, dtype=torch.float32)
        self.y = torch.tensor(y.reshape(-1, 1), dtype=torch.float32)

    def __len__(self) -> int:
        return len(self.X)

    def __getitem__(self, idx: int):
        return self.X[idx], self.y[idx]


def standardize_columns(df: pd.DataFrame) -> pd.DataFrame:
    df = df.copy()
    df.columns = [str(c).strip() for c in df.columns]
    return df


def ensure_required_columns(
    df: pd.DataFrame,
    required_cols: Iterable[str],
    source_name: str,
) -> None:
    missing = [c for c in required_cols if c not in df.columns]

    if missing:
        raise ValueError(f"{source_name} is missing required columns: {missing}")


def load_coin_csv(path: str | Path, symbol: str) -> pd.DataFrame:
    """
    Loads one coin CSV generated by your Binance feature script.

    Expected columns:
        date, open, high, low, close, volume,
        log_ret_close, log_ret_vol, volatility, rsi, macd

    Existing target column is ignored and recomputed later per coin.
    """
    path = Path(path)

    if not path.exists():
        raise FileNotFoundError(f"Dataset file not found: {path}")

    df = pd.read_csv(path)
    df = standardize_columns(df)

    required_cols = [
        "date",
        "open",
        "high",
        "low",
        "close",
        "volume",
        "log_ret_close",
        "log_ret_vol",
        "volatility",
        "rsi",
        "macd",
    ]

    ensure_required_columns(df, required_cols, str(path))

    df["symbol"] = symbol
    df["date"] = pd.to_datetime(df["date"], utc=True, errors="coerce")

    numeric_cols = [
        "open",
        "high",
        "low",
        "close",
        "volume",
        "log_ret_close",
        "log_ret_vol",
        "volatility",
        "rsi",
        "macd",
    ]

    for col in numeric_cols:
        df[col] = pd.to_numeric(df[col], errors="coerce")

    df = df.dropna(subset=["date"])
    df = df.sort_values("date").reset_index(drop=True)

    return df


def load_btc_eth_data(
    btc_path: str | Path,
    eth_path: str | Path,
) -> pd.DataFrame:
    btc_df = load_coin_csv(btc_path, symbol="BTCUSDT")
    eth_df = load_coin_csv(eth_path, symbol="ETHUSDT")

    df = pd.concat([btc_df, eth_df], ignore_index=True)
    df = df.sort_values(["symbol", "date"]).reset_index(drop=True)

    # Important:
    # Recompute target safely inside each coin.
    # This avoids BTC rows ever using ETH future rows.
    df[TARGET_COL] = df.groupby("symbol")["log_ret_close"].shift(-1)

    df["coin_BTC"] = (df["symbol"] == "BTCUSDT").astype(float)
    df["coin_ETH"] = (df["symbol"] == "ETHUSDT").astype(float)

    return df


def split_by_time_per_coin(
    df: pd.DataFrame,
    train_ratio: float,
    val_ratio: float,
) -> tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    """
    Splits each coin chronologically, then combines BTC+ETH parts.

    This avoids future leakage.
    """
    if train_ratio <= 0 or train_ratio >= 1:
        raise ValueError("train_ratio must be between 0 and 1.")

    if val_ratio <= 0 or val_ratio >= 1:
        raise ValueError("val_ratio must be between 0 and 1.")

    if train_ratio + val_ratio >= 1:
        raise ValueError("train_ratio + val_ratio must be less than 1.")

    train_parts = []
    val_parts = []
    test_parts = []

    for symbol, coin_df in df.groupby("symbol"):
        coin_df = coin_df.sort_values("date").reset_index(drop=True)

        n = len(coin_df)
        train_end = int(n * train_ratio)
        val_end = int(n * (train_ratio + val_ratio))

        train_parts.append(coin_df.iloc[:train_end].copy())
        val_parts.append(coin_df.iloc[train_end:val_end].copy())
        test_parts.append(coin_df.iloc[val_end:].copy())

    train_df = pd.concat(train_parts, ignore_index=True)
    val_df = pd.concat(val_parts, ignore_index=True)
    test_df = pd.concat(test_parts, ignore_index=True)

    return train_df, val_df, test_df


def scale_splits(
    train_df: pd.DataFrame,
    val_df: pd.DataFrame,
    test_df: pd.DataFrame,
    feature_cols: list[str],
    target_col: str = TARGET_COL,
) -> tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame, StandardScaler, StandardScaler]:
    """
    Correct global scaling:

        feature_scaler.fit(BTC_train + ETH_train)
        target_scaler.fit(BTC_train_target + ETH_train_target)

    Validation/test are only transformed, never fitted.

    Coin identity columns are not scaled.
    """
    train_df = train_df.copy()
    val_df = val_df.copy()
    test_df = test_df.copy()

    continuous_feature_cols = [c for c in feature_cols if c not in COIN_ID_COLS]

    feature_scaler = StandardScaler()
    target_scaler = StandardScaler()

    train_df[continuous_feature_cols] = feature_scaler.fit_transform(
        train_df[continuous_feature_cols]
    )
    val_df[continuous_feature_cols] = feature_scaler.transform(
        val_df[continuous_feature_cols]
    )
    test_df[continuous_feature_cols] = feature_scaler.transform(
        test_df[continuous_feature_cols]
    )

    train_df[[target_col]] = target_scaler.fit_transform(train_df[[target_col]])
    val_df[[target_col]] = target_scaler.transform(val_df[[target_col]])
    test_df[[target_col]] = target_scaler.transform(test_df[[target_col]])

    return train_df, val_df, test_df, feature_scaler, target_scaler


def make_sequence_arrays(
    df: pd.DataFrame,
    feature_cols: list[str],
    target_col: str = TARGET_COL,
    sequence_length: int = SEQUENCE_LENGTH,
) -> tuple[np.ndarray, np.ndarray]:
    """
    Builds sliding windows separately per coin.

    For every sample:
        X = previous 30 days of selected features
        y = next day's log_ret_close target at current row

    Output:
        X: [samples, 30, num_features]
        y: [samples]
    """
    X = []
    y = []

    for symbol, coin_df in df.groupby("symbol"):
        coin_df = coin_df.sort_values("date").reset_index(drop=True)

        values = coin_df[feature_cols].to_numpy(dtype=np.float32)
        targets = coin_df[target_col].to_numpy(dtype=np.float32)

        for i in range(sequence_length, len(coin_df)):
            X_window = values[i - sequence_length : i]
            y_value = targets[i]

            if np.isnan(X_window).any() or np.isnan(y_value):
                continue

            X.append(X_window)
            y.append(y_value)

    if len(X) == 0:
        raise ValueError(
            "No sequence samples were created. "
            "Check NaN values, date range, and sequence length."
        )

    return np.asarray(X, dtype=np.float32), np.asarray(y, dtype=np.float32)


def flatten_sequences(X_seq: np.ndarray) -> np.ndarray:
    """
    Converts sequence data for XGBoost.

        [samples, 30, num_features]
        ↓
        [samples, 30 * num_features]

    This keeps the same 30-day lookback for XGBoost.
    """
    return X_seq.reshape(X_seq.shape[0], -1)


def prepare_data_for_feature_set(
    btc_path: str | Path,
    eth_path: str | Path,
    base_feature_cols: list[str],
    include_coin_identity: bool,
    sequence_length: int,
    batch_size: int,
    train_ratio: float,
    val_ratio: float,
) -> PreparedData:
    df = load_btc_eth_data(btc_path=btc_path, eth_path=eth_path)

    feature_cols = list(base_feature_cols)

    if include_coin_identity:
        feature_cols += COIN_ID_COLS

    required_cols = feature_cols + [TARGET_COL, "symbol", "date"]
    ensure_required_columns(df, required_cols, "BTC+ETH dataframe")

    # Drop unusable rows for this specific feature set.
    df = df.dropna(subset=feature_cols + [TARGET_COL]).reset_index(drop=True)

    train_df, val_df, test_df = split_by_time_per_coin(
        df=df,
        train_ratio=train_ratio,
        val_ratio=val_ratio,
    )

    train_df, val_df, test_df, feature_scaler, target_scaler = scale_splits(
        train_df=train_df,
        val_df=val_df,
        test_df=test_df,
        feature_cols=feature_cols,
        target_col=TARGET_COL,
    )

    X_train_seq, y_train = make_sequence_arrays(
        train_df,
        feature_cols=feature_cols,
        target_col=TARGET_COL,
        sequence_length=sequence_length,
    )

    X_val_seq, y_val = make_sequence_arrays(
        val_df,
        feature_cols=feature_cols,
        target_col=TARGET_COL,
        sequence_length=sequence_length,
    )

    X_test_seq, y_test = make_sequence_arrays(
        test_df,
        feature_cols=feature_cols,
        target_col=TARGET_COL,
        sequence_length=sequence_length,
    )

    train_dataset = CryptoSequenceDataset(X_train_seq, y_train)
    val_dataset = CryptoSequenceDataset(X_val_seq, y_val)
    test_dataset = CryptoSequenceDataset(X_test_seq, y_test)

    train_loader = DataLoader(
        train_dataset,
        batch_size=batch_size,
        shuffle=True,
    )
    val_loader = DataLoader(
        val_dataset,
        batch_size=batch_size,
        shuffle=False,
    )
    test_loader = DataLoader(
        test_dataset,
        batch_size=batch_size,
        shuffle=False,
    )

    return PreparedData(
        feature_cols=feature_cols,
        target_col=TARGET_COL,
        sequence_length=sequence_length,

        train_df=train_df,
        val_df=val_df,
        test_df=test_df,

        X_train_seq=X_train_seq,
        y_train=y_train,
        X_val_seq=X_val_seq,
        y_val=y_val,
        X_test_seq=X_test_seq,
        y_test=y_test,

        X_train_flat=flatten_sequences(X_train_seq),
        X_val_flat=flatten_sequences(X_val_seq),
        X_test_flat=flatten_sequences(X_test_seq),

        train_loader=train_loader,
        val_loader=val_loader,
        test_loader=test_loader,

        feature_scaler=feature_scaler,
        target_scaler=target_scaler,
    )
